import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceFiles = [
  'src/simulation/SeededRandom.js',
  'src/simulation/ConveyorEngineering.js',
  'src/simulation/FormatGeometryAdapter.js',
  'src/simulation/SimulationValidation.js',
  'src/simulation/LineSimulationEngine.js',
  'src/simulation/SimulationBatch.js',
  'src/simulation/SimulationWorkers.js',
  'src/analysis/LinePerformanceAnalysis.js',
  'src/analysis/ScenarioPlanner.js',
  'src/analysis/ScenarioDOE.js'
];
const targetFile = path.join(repositoryRoot, 'apps-script', 'SimulationEngine.html');

const source = sourceFiles
  .map((relativePath) => fs.readFileSync(path.join(repositoryRoot, relativePath), 'utf8'))
  .map(removeModuleSyntax)
  .join('\n\n');

const output = `<script>
/* Generated by scripts/build-browser-engine.mjs. Do not edit directly. */
(function engineRuntime(window, workerMode) {
'use strict';

${source}

if(workerMode){
  window.onmessage=async function(event){
    const task=event.data;
    try {
      const response=await simulateLineAsync(task.input,{detail:task.detail,summaryOnly:task.summaryOnly,yieldBetweenChunks:false,progress:value=>window.postMessage({type:'progress',id:task.id,value})});
      window.postMessage({type:'result',id:task.id,response});
    }catch(error){window.postMessage({type:'error',id:task.id,message:error.message});}
  };
  window.postMessage({type:'ready'});return;
}
let workerPool,workersUnavailable=false;
async function simulateBrowserBatch(input,options={}){
  const settings={...options,laterSummaryOnly:options.laterSummaryOnly!==false};
  const count=input.run.rounds||1;
  if(count<2||options.parallel===false||workersUnavailable||typeof window.Worker!=='function'||!window.Blob||!window.URL?.createObjectURL)return simulateBatch(input,settings);
  if(!workerPool){
    const size=Math.min(4,Math.max(1,(window.navigator?.hardwareConcurrency||3)-1));
    workerPool=createSimulationWorkerPool(()=>{
      const url=window.URL.createObjectURL(new window.Blob(['('+engineRuntime.toString()+')(self,true);'],{type:'text/javascript'}));
      try{return new window.Worker(url);}finally{window.URL.revokeObjectURL(url);}
    },size);
  }
  try{return await simulateBatch(input,{...settings,runRound:workerPool.run,concurrency:workerPool.size});}
  catch(error){
    if(error.message!=='SIMULATION_WORKER_UNAVAILABLE')throw error;
    workersUnavailable=true;workerPool?.close(new Error('SIMULATION_WORKER_UNAVAILABLE'));workerPool=null;
    if(options.cancelled?.())throw new Error('BATCH_CANCELLED');
    return simulateBatch(input,settings);
  }
}
window.addEventListener?.('pagehide',()=>{workerPool?.close();workerPool=null;});
window.SimulatorEngine = {
  simulateLine: simulateLine,
  simulateBatch: simulateBrowserBatch,
  simulateLineAsync: simulateLineAsync,
  validateSimulationInput: validateSimulationInput,
  calculateConveyorEngineering: calculateConveyorEngineering,
  analyzeLinePerformance: analyzeLinePerformance
};
window.STScenarioDOE = {design:createScenarioDOE,analyze:analyzeScenarioDOE};
window.STScenarios = {plan:planScenarios,apply:applyScenarioChanges,signature:scenarioSignature,audit:scenarioAudit,fields:SCENARIO_FIELDS};
})(window,false);
</script>
`;

fs.writeFileSync(targetFile, output);

const scenarioSources = ['src/simulation/ConveyorEngineering.js','src/simulation/FormatGeometryAdapter.js','src/simulation/SimulationValidation.js','src/analysis/LinePerformanceAnalysis.js','src/analysis/ScenarioPlanner.js'];
fs.writeFileSync(path.join(repositoryRoot,'apps-script','ScenarioEngine.gs'),
  '// GENERATED scenario validation and planning. Edit src/analysis/ScenarioPlanner.js.\nvar STScenarioEngine_ = (function(){\n'+
  scenarioSources.map(file=>removeModuleSyntax(fs.readFileSync(path.join(repositoryRoot,file),'utf8'))).join('\n')+
  '\nreturn {plan:planScenarios,apply:applyScenarioChanges,signature:scenarioSignature,audit:scenarioAudit,fields:SCENARIO_FIELDS};\n})();\n');

function removeModuleSyntax(moduleSource) {
  return moduleSource
    .replace(/^import .*;\n/gm, '')
    .replace(/^export /gm, '');
}
